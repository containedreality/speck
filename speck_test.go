package speck_test

import (
	"bytes"
	"log"
	"testing"

	"github.com/containedreality/speck"
)

func TestSpeck128_128(t *testing.T) {
	key := []byte{0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f}

	block, err := speck.New128(key)
	if err != nil {
		log.Println(err)
		t.Fail()
	}

	plaintext := []byte{0x20, 0x6d, 0x61, 0x64,
		0x65, 0x20, 0x69, 0x74,
		0x20, 0x65, 0x71, 0x75,
		0x69, 0x76, 0x61, 0x6c,
	}

	v := []byte{0x18, 0x0d, 0x57, 0x5c, 0xdf, 0xfe, 0x60, 0x78, 0x65, 0x32, 0x78, 0x79, 0x51, 0x98, 0x5d, 0xa6}

	buf := make([]byte, 16)
	block.Encrypt(buf, plaintext)

	if !bytes.Equal(buf, v) {
		log.Print(buf)
		t.Fail()
	}

	decbuf := make([]byte, 16)
	block.Decrypt(decbuf, buf)

	if !bytes.Equal(decbuf, plaintext) {
		log.Print(buf)
		t.Fail()
	}
}

